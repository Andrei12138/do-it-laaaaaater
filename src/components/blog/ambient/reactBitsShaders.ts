export function shaderSource(body: string, webgl2: boolean, vertex = false, derivatives = false) {
  const header = webgl2 ? '#version 300 es\n' : derivatives ? '#extension GL_OES_standard_derivatives : require\n' : ''
  return `${header}precision highp float;
precision highp int;
#define ATTR ${webgl2 ? 'in' : 'attribute'}
#define VARY ${webgl2 ? vertex ? 'out' : 'in' : 'varying'}
#define SAMPLE ${webgl2 ? 'texture' : 'texture2D'}
${vertex ? '' : webgl2 ? 'out vec4 PIXEL;' : '#define PIXEL gl_FragColor\n#define tanh(x) (2.0 / (1.0 + exp(-2.0 * (x))) - 1.0)'}
${body}`
}

